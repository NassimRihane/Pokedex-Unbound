import Foundation

/// One entry of the Pokedex list (a species or a regional form).
///
/// Each Pokemon is backed by two bundled files sharing the same base name,
/// e.g. "037_vulpix-alola.json" and "037_vulpix-alola.png".
struct Pokemon: Identifiable, Hashable {
    /// Base name of the bundled files, e.g. "037_vulpix-alola". Unique for every entry.
    let fileName: String
    /// National Pokedex number, e.g. 37. A regional form shares it with its base species.
    let dexNumber: Int
    /// PokeAPI name, e.g. "vulpix-alola". Unique, also used as the key of the capture tracker.
    let name: String
    /// Name shown in the interface, e.g. "Alolan Vulpix" or "Mr. Mime".
    let displayName: String
    /// Generation that introduced this entry (a regional form has its own, e.g. 7 for Alola).
    let generation: Int
    
    var id: String { fileName }
    
    /// "#037"
    var formattedDexNumber: String {
        String(format: "#%03d", dexNumber)
    }
    
    static var samplePokemon = Pokemon(fileName: "001_bulbasaur", dexNumber: 1, name: "bulbasaur", displayName: "Bulbasaur", generation: 1)
}

/// One entry of pokedex-index.json (generated by build_index.py).
/// Holds everything the main list needs, so the full JSON files are only read on the detail pages.
struct PokemonIndexEntry: Codable {
    let file: String
    let dex: Int
    let name: String
    let nameEn: String
    let nameJp: String?
    let nameFr: String?
    let generation: Int
    let form: String?
    let types: [String]
    let stats: IndexStats
    
    struct IndexStats: Codable {
        let hp: Int
        let attack: Int
        let defense: Int
        let specialAttack: Int
        let specialDefense: Int
        let speed: Int
    }
}

struct DetailPokemon: Codable {
    let id: Int
    let name: String
    let nameJp: String
    let nameFr: String
    let nameEn: String?
    let height: Int
    let weight: Int
    let abilities: [AbilityEntry]
    let moves: [MoveEntry]
    let sprites: Sprites
    let stats: [Stat]
    let types: [TypeEntry]
    let location_encounters_by_generation: LocationEncountersByGeneration?
    let evolution_chain: [EvolutionNode]?
    
    enum CodingKeys: String, CodingKey {
        case id, name, height, weight, abilities, moves, sprites, stats, types
        case nameJp = "name-jp"
        case nameFr = "name-fr"
        case nameEn = "name-en"
        case location_encounters_by_generation
        case evolution_chain
    }

    
    struct MoveEntry: Codable {
        let move: MoveDetails
        let level_learned_at: Int
        let move_learn_method: String
        let version_group: String
    }
    
    struct MoveDetails: Codable {
        let name: String
        let type: String?
        let power: Int?
        let pp: Int?
        let accuracy: Int?
    }
    
    struct AbilityEntry: Codable {
        let ability: AbilityDetails
        let is_hidden: Bool
        let slot: Int
    }
    
    struct AbilityDetails: Codable {
        let name: String
        let description: String
    }
    
    struct Sprites: Codable {
        let front_default: String?
    }
    
    struct Stat: Codable {
        let base_stat: Int
        let stat: NamedAPIResource
    }
    
    struct TypeEntry: Codable {
        let slot: Int
        let type: NamedAPIResource
    }
    
    struct NamedAPIResource: Codable {
        let name: String
        let url: String
    }
    
    struct LocationAreaEncounter: Codable {
        let location_area: NamedAPIResource
    }
}

extension DetailPokemon.MoveEntry{
    var uniqueID : String{
        return "\(move.name)_\(move_learn_method)_\(level_learned_at)_\(version_group)"
    }
}

/// One stage of an evolution tree (generated by data_fetcher.py).
struct EvolutionNode: Codable, Identifiable {
    /// PokeAPI name, e.g. "ninetales-alola"
    let name: String
    /// Base name of the bundled files, e.g. "038_ninetales-alola"
    let file: String
    let dex: Int
    /// How the previous stage evolves into this one, e.g. "Use Ice Stone" (nil for the first stage)
    let condition: String?
    let evolves_to: [EvolutionNode]
    
    var id: String { file }
}
